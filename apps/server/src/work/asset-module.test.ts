import { it, expect } from 'vitest';
import ts from 'typescript';
import { insertModuleSource, moduleComponentSource, removeModuleSource } from './asset-module.ts';

const id = 'a'.repeat(32);
const other = 'b'.repeat(32);

function locationOf(source: string, needle: string) {
  const tree = ts.createSourceFile('src/App.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const offset = source.indexOf(needle);
  const at = tree.getLineAndCharacterOfPosition(offset);
  return { line: at.line + 1, column: at.character + 1 };
}

it('wraps an exact JSX anchor and imports the managed instance, not a model URL', () => {
  const source = 'export default function App(){return <main><button onClick={()=>alert(1)}>Buy</button></main>;}';
  const at = locationOf(source, '<button');
  const result = insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'after' }, id);
  expect(result).toContain('<button onClick={()=>alert(1)}>Buy</button>');
  expect(result).toContain(`<SpatialModel${id}/>`);
  expect(result).toContain(`"./scene-modules/${id}"`);
  expect(result).not.toContain('.glb');
  expect(result).not.toContain('scene.config.json');
});

it('rejects stale anchors, main/model targets and non-insert intents', () => {
  const source = 'export default ()=> <main><ProductHero/><SpatialModel' + other + '/></main>;';
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: 'src/App.tsx:999:1', cid: 'Node', ancestors: [], position: 'after' }, id)).toThrow();
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: 'src/../outside.tsx:1:1', cid: 'Node', ancestors: [], position: 'after' }, id)).toThrow();
  const hero = locationOf(source, '<ProductHero');
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${hero.line}:${hero.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
  const model = locationOf(source, '<SpatialModel' + other);
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${model.line}:${model.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
  const button = 'export default ()=> <main><button/></main>;';
  const at = locationOf(button, '<button');
  expect(() => insertModuleSource(button, 'src/App.tsx', { kind: 'replace', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
});

it('removes the exact instance reference and its managed import while preserving the page element', () => {
  const original = 'export default function App(){return <main><button onClick={()=>alert(1)}>Buy</button></main>;}';
  const at = locationOf(original, '<button');
  const inserted = insertModuleSource(original, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'before' }, id);
  const removed = removeModuleSource(inserted, 'src/App.tsx', id);
  expect(removed).toBe(original);
  expect(() => removeModuleSource(original, 'src/App.tsx', id)).toThrow();
});

it('generated components carry only the instance id and match the managed tree contract', () => {
  const source = moduleComponentSource(id);
  expect(source).toBe(`// Generated by Spatial AI Workbench. Do not edit.\nimport { SpatialModule } from '../spatial-module';\nexport default function SpatialModel${id}() { return <SpatialModule instanceId="${id}" />; }\n`);
  expect(source).not.toContain('.glb');
  expect(() => moduleComponentSource('../escape')).toThrow();
});
