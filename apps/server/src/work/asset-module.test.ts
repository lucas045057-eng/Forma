import { it, expect } from 'vitest';
import ts from 'typescript';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { ensureModuleRuntime, installAssetFiles, insertModuleSource, moduleComponentSource, removeModuleSource } from './asset-module.ts';

const id = 'a'.repeat(32);
const other = 'b'.repeat(32);

function locationOf(source: string, needle: string) {
  const tree = ts.createSourceFile('src/App.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const offset = source.indexOf(needle);
  const at = tree.getLineAndCharacterOfPosition(offset);
  return { line: at.line + 1, column: at.character + 1 };
}

it('wraps an exact JSX anchor and imports the managed instance, not a model URL', () => {
  const source = 'export default function App(){return <main><button onClick={()=>alert(1)}>Buy</button></main>;}';
  const at = locationOf(source, '<button');
  const result = insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'after' }, id);
  expect(result).toContain('<button onClick={()=>alert(1)}>Buy</button>');
  expect(result).toContain(`<SpatialModel${id}/>`);
  expect(result).toContain(`"./scene-modules/${id}.tsx"`);
  expect(result).not.toContain('.glb');
  expect(result).not.toContain('scene.config.json');
});

it('rejects stale anchors, main/model targets and non-insert intents', () => {
  const source = 'export default ()=> <main><ProductHero/><SpatialModel' + other + '/></main>;';
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: 'src/App.tsx:999:1', cid: 'Node', ancestors: [], position: 'after' }, id)).toThrow();
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: 'src/../outside.tsx:1:1', cid: 'Node', ancestors: [], position: 'after' }, id)).toThrow();
  const hero = locationOf(source, '<ProductHero');
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${hero.line}:${hero.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
  const model = locationOf(source, '<SpatialModel' + other);
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${model.line}:${model.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
  const button = 'export default ()=> <main><button/></main>;';
  const at = locationOf(button, '<button');
  expect(() => insertModuleSource(button, 'src/App.tsx', { kind: 'replace', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'after' }, id)).toThrow();
});

it('removes the exact instance reference and its managed import while preserving the page element', () => {
  const original = 'export default function App(){return <main><button onClick={()=>alert(1)}>Buy</button></main>;}';
  const at = locationOf(original, '<button');
  const inserted = insertModuleSource(original, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'before' }, id);
  const removed = removeModuleSource(inserted, 'src/App.tsx', id);
  expect(removed).toBe(original);
  expect(() => removeModuleSource(original, 'src/App.tsx', id)).toThrow();
});

it('rejects inside insertion on a self-closing element instead of silently changing position', () => {
  const source = 'export default ()=> <main><img src="x"/></main>;';
  const at = locationOf(source, '<img');
  expect(() => insertModuleSource(source, 'src/App.tsx', { kind: 'insert', src: `src/App.tsx:${at.line}:${at.column}`, cid: 'App', ancestors: [], position: 'inside' }, id)).toThrow(/INSIDE_REQUIRES_CONTAINER|内部空间/);
});

it('server migration installs the exact trusted runtime only when the work has none', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'module-runtime-'));
  try {
    const root = path.join(directory, 'work');
    await mkdir(path.join(root, 'src'), { recursive: true });
    const first = await ensureModuleRuntime(root);
    expect(first?.path).toBe('src/spatial-module.tsx');
    expect(first?.role).toBe('runtime');
    const text = await readFile(path.join(root, 'src', 'spatial-module.tsx'), 'utf8');
    expect(text).toContain('export function SpatialModule');
    expect(await ensureModuleRuntime(root)).toBeUndefined();
    await writeFile(path.join(root, 'src', 'spatial-module.ts'), 'export {}');
    await expect(ensureModuleRuntime(root)).rejects.toMatchObject({ code: 'MODULE_RUNTIME_CONFLICT' });
  } finally { await rm(directory, { recursive: true, force: true }); }
});

it('generated components carry only the instance id and match the managed tree contract', () => {
  const source = moduleComponentSource(id);
  expect(source).toBe(`// Generated by Spatial AI Workbench. Do not edit.\nimport { SpatialModule } from '../spatial-module.tsx';\nexport default function SpatialModel${id}() { return <SpatialModule instanceId="${id}" />; }\n`);
  expect(source).not.toContain('.glb');
  expect(() => moduleComponentSource('../escape')).toThrow();
});

it('reuses already-adopted public asset files (including legacy parts.json without trailing LF) while rejecting real conflicts', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'module-install-assets-'));
  try {
    const root = path.join(directory, 'work');
    await mkdir(root, { recursive: true });
    const binary = Buffer.from('glTF-shared-model');
    const provenance = {
      schemaVersion: 1 as const,
      kind: 'lux3d' as const,
      sourceTaskId: '1001',
      outputHash: createHash('sha256').update(binary).digest('hex'),
    };
    const parts = { recognized: false, nodes: [], reason: 'No part metadata' };

    const created = await installAssetFiles({ root, assetId: 'opt-1', binary, provenance, parts });
    expect(created).toHaveLength(3);
    expect(await installAssetFiles({ root, assetId: 'opt-1', binary, provenance, parts })).toEqual([]);

    // Simulate a legacy main-slot adoption that wrote parts.json without trailing newline.
    const partsFile = path.join(root, 'public', 'assets', 'opt-1.parts.json');
    const legacyParts = JSON.stringify(parts, null, 2);
    await writeFile(partsFile, legacyParts);
    expect(await installAssetFiles({ root, assetId: 'opt-1', binary, provenance, parts })).toEqual([]);
    expect(await readFile(partsFile, 'utf8')).toBe(legacyParts);

    // Real content differences must still be rejected as ASSET_NAME_CONFLICT.
    await expect(installAssetFiles({ root, assetId: 'opt-1', binary, provenance, parts: { recognized: true, nodes: [] } }))
      .rejects.toMatchObject({ code: 'ASSET_NAME_CONFLICT' });
    await expect(installAssetFiles({ root, assetId: 'opt-1', binary: Buffer.from('different'), provenance, parts }))
      .rejects.toMatchObject({ code: 'ASSET_NAME_CONFLICT' });
  } finally { await rm(directory, { recursive: true, force: true }); }
});
