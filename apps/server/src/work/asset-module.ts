async function existingBytes(file: string): Promise<Buffer | undefined> {
  try { return await readFile(file); } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; }
}
function digest(bytes: Buffer): string { return createHash('sha256').update(bytes).digest('hex'); }

export function moduleComponentSource(instanceId: string): string {
  if (!/^[a-f0-9]{32}$/.test(instanceId)) throw new WorkError('INVALID_MODULE', '模块实例编号必须由服务端产生');
  return `// Generated by Spatial AI Workbench. Do not edit.\nimport { SpatialModule } from '../spatial-module.tsx';\nexport default function SpatialModel${instanceId}() { return <SpatialModule instanceId="${instanceId}" />; }\n`;
}

function validateRuntimeBytes(bytes: Buffer): void {
  if (!isTrustedRuntimeSource(bytes.toString('utf8'))) {
    throw new WorkError('MODULE_RUNTIME_INVALID', '受信 3D 模块运行时内容不符合约定', 409);
  }
}

async function builtInRuntime(): Promise<Buffer> {
  const file = fileURLToPath(new URL('../../../../templates/product-page/src/spatial-module.tsx', import.meta.url));
  const bytes = await readFile(file).catch(() => undefined);
  if (!bytes || bytes.length > 64 * 1024) throw new WorkError('MODULE_RUNTIME_MISSING', '服务端内置受信 3D 运行时不可用', 500);
  validateRuntimeBytes(bytes);
  return bytes;
}

/** Reject any same-name sibling/directory that could shadow the canonical `.tsx` runtime. */
async function assertNoRuntimeShadow(root: string): Promise<string[]> {
  const directory = await safeWorkPath(root, 'src');
  let names: string[];
  try { names = await readdir(directory); } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return []; throw error; }
  const base = path.posix.basename(SCENE_MODULE_RENDERER_BASE);
  return names.filter(name => {
    const normalized = name.toLowerCase();
    return normalized === base || normalized.startsWith(`${base}.`);
  });
}

/** Validate an existing runtime without installing anything (used before candidate work). */
export async function assertModuleRuntime(root: string): Promise<void> {
  const shadows = await assertNoRuntimeShadow(root);
  if (shadows.length && shadows.some(name => name.toLowerCase() !== 'spatial-module.tsx')) {
    throw new WorkError('MODULE_RUNTIME_CONFLICT', '作品中存在可劫持受信运行时的同名文件或目录，请先人工处理', 409);
  }
  const bytes = await existingBytes(await safeWorkPath(root, SCENE_MODULE_RENDERER));
  if (!bytes) throw new WorkError('MODULE_RUNTIME_MISSING', '当前作品缺少受信 3D 模块运行时', 409);
  validateRuntimeBytes(bytes);
}

/**
 * Server-only migration: install the exact built-in renderer into a candidate when an older work
 * has none. A custom same-name file or directory is never overwritten.
 */
export async function ensureModuleRuntime(root: string): Promise<AssetFileDraft | undefined> {
  const shadows = await assertNoRuntimeShadow(root);
  const canonical = shadows.filter(name => name.toLowerCase() === 'spatial-module.tsx');
  const conflicts = shadows.filter(name => name.toLowerCase() !== 'spatial-module.tsx');
  if (conflicts.length) throw new WorkError('MODULE_RUNTIME_CONFLICT', '作品中存在可劫持受信运行时的同名文件或目录，不能自动安装', 409);
  if (canonical.length) {
    const bytes = await existingBytes(await safeWorkPath(root, SCENE_MODULE_RENDERER));
    if (!bytes) throw new WorkError('MODULE_RUNTIME_INVALID', '受信运行时路径异常', 409);
    validateRuntimeBytes(bytes);
    return undefined;
  }
  const bytes = await builtInRuntime();
  const target = await safeWorkPath(root, SCENE_MODULE_RENDERER);
  await mkdir(path.dirname(target), { recursive: true });
  await writeAtomic(target, bytes);
  return { path: SCENE_MODULE_RENDERER, operation: 'create', role: 'runtime', beforeHash: null, afterHash: digest(bytes), bytes: bytes.length };
}

export async function ensureModuleTsConfig(root: string): Promise<AssetFileDraft | undefined> {
  const target = await safeWorkPath(root, 'tsconfig.json');
  const before = await existingBytes(target);
  if (!before) throw new WorkError('MODULE_TS_CONFIG_INCOMPATIBLE', '作品缺少 tsconfig.json，不能安装显式 .tsx 导入的受信模块', 409);
  let parsed: unknown;
  try { parsed = JSON.parse(before.toString('utf8')); }
  catch { throw new WorkError('MODULE_TS_CONFIG_INCOMPATIBLE', '作品 tsconfig.json 不是可安全合并的 JSON；请由维护者处理', 409); }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new WorkError('MODULE_TS_CONFIG_INCOMPATIBLE', '作品 tsconfig.json 结构无效', 409);
  const input = parsed as Record<string, unknown>;
  const compiler = input.compilerOptions;
  if (!compiler || typeof compiler !== 'object' || Array.isArray(compiler)) throw new WorkError('MODULE_TS_CONFIG_INCOMPATIBLE', '作品 tsconfig.json 缺少 compilerOptions', 409);
  const options = compiler as Record<string, unknown>;
  if (options.allowImportingTsExtensions === true) return undefined;
  if (options.noEmit !== true) throw new WorkError('MODULE_TS_CONFIG_INCOMPATIBLE', '显式 .tsx 导入需要 noEmit:true；不能改写作品的编译语义', 409);
  const next = { ...input, compilerOptions: { ...options, allowImportingTsExtensions: true } };
  const bytes = Buffer.from(JSON.stringify(next, null, 2) + '\n');
  await writeAtomic(target, bytes);
  return { path: 'tsconfig.json', operation: 'modify', role: 'tsconfig', beforeHash: digest(before), afterHash: digest(bytes), bytes: bytes.length };
}

export function insertModuleSource(source: string, filename: string, target: AssetPlacementTarget, instanceId: string): string {
  const match = /^(src\/[A-Za-z0-9_./-]+):([1-9]\d*):([1-9]\d*)$/.exec(target.src);
  if (!match || match[1].split('/').includes('..')) throw new WorkError('INVALID_PLACEMENT_TARGET', '放置源码身份无效');
  if (target.kind !== 'insert') throw new WorkError('INVALID_PLACEMENT_TARGET', '只有普通区域可以插入新模块');
  const tree = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const position = tree.getPositionOfLineAndCharacter(Number(match[2]) - 1, Number(match[3]) - 1);
  let anchor: ts.JsxElement | ts.JsxSelfClosingElement | undefined;
  function visit(node: ts.Node) {
    if ((ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) && node.getStart(tree) === position) anchor = node;
    ts.forEachChild(node, visit);
  }
  visit(tree);
  if (!anchor) throw new WorkError('STALE_PLACEMENT_TARGET', '页面源码位置已变化或目标不支持插入', 409);
  const node = anchor;
  const tag = ts.isJsxElement(node) ? node.openingElement.tagName.getText(tree) : node.tagName.getText(tree);
  if (tag.startsWith('SpatialModel') || tag === 'SpatialModule' || tag === 'ProductScene' || tag === 'ProductHero') {
    throw new WorkError('INVALID_PLACEMENT_TARGET', '该位置是已有 3D 展示区，请选择替换而不是新增', 409);
  }
  const component = `SpatialModel${instanceId}`;
  const jsx = `<${component}/>`;
  const before = source.slice(0, node.getStart(tree));
  const selected = source.slice(node.getStart(tree), node.end);
  const after = source.slice(node.end);
  if (target.position === 'inside' && ts.isJsxSelfClosingElement(node)) throw new WorkError('INSIDE_REQUIRES_CONTAINER', '自闭合元素没有内部空间，请选择插在它之前或之后', 409);
  const inserted = target.position === 'inside' && ts.isJsxElement(node)
    ? selected.slice(0, node.openingElement.end - node.getStart(tree)) + jsx + selected.slice(node.openingElement.end - node.getStart(tree))
    : target.position === 'before' ? `<>${jsx}${selected}</>` : `<>${selected}${jsx}</>`;
  const importPath = path.posix.relative(path.posix.dirname(match[1]), `${SCENE_MODULE_DIRECTORY}/${instanceId}.tsx`).replace(/^(?!\.)/, './');
  return `import ${component} from ${JSON.stringify(importPath)};\n` + before + inserted + after;
}

export interface AssetFileDraft {
  path: string;
  operation: LedgerEntry['operation'];
  role: LedgerEntry['role'];
  beforeHash: string | null;
  afterHash: string | null;
  bytes: number;
  assetId?: string;
  instanceId?: string;
}

export async function readModuleConfig(root: string, instanceId: string): Promise<SceneModuleConfig> {
  const file = await safeWorkPath(root, moduleConfigPath(instanceId));
  const bytes = await existingBytes(file);
  if (!bytes) throw new WorkError('MODULE_NOT_FOUND', '独立3D实例不存在', 404);
  if (bytes.length > 16 * 1024) throw new WorkError('INVALID_MODULE', '独立3D实例配置过大', 409);
  let parsed: unknown;
  try { parsed = JSON.parse(bytes.toString('utf8')); } catch { throw new WorkError('INVALID_MODULE', '独立3D实例配置损坏', 409); }
  try { return parseSceneModuleConfig(parsed); } catch { throw new WorkError('INVALID_MODULE', '独立3D实例配置不符合约束', 409); }
}

export async function listModuleConfigs(root: string): Promise<SceneModuleConfig[]> {
  const directory = await safeWorkPath(root, SCENE_MODULE_DIRECTORY);
  let names: string[];
  try { names = await readdir(directory); } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return []; throw error; }
  const result: SceneModuleConfig[] = [];
  for (const name of names.sort()) {
    if (!/^[a-f0-9]{32}\.json$/.test(name)) continue;
    try { result.push(await readModuleConfig(root, name.slice(0, 32))); }
    catch (error) { if (error instanceof WorkError && error.code === 'MODULE_NOT_FOUND') continue; throw error; }
  }
  return result;
}

export async function installAssetFiles(input: { root: string; assetId: string; binary: Buffer; provenance: ModelProvenance; parts?: unknown }): Promise<AssetFileDraft[]> {
  const drafts: AssetFileDraft[] = [];
  const files: Array<{ relative: string; role: LedgerEntry['role']; bytes: Buffer }> = [
    { relative: `public/assets/${input.assetId}.glb`, role: 'model', bytes: input.binary },
    { relative: `public/assets/${input.assetId}.provenance.json`, role: 'provenance', bytes: Buffer.from(JSON.stringify(input.provenance, null, 2) + '\n') },
  ];
  if (input.parts !== undefined) files.push({ relative: `public/assets/${input.assetId}.parts.json`, role: 'parts', bytes: Buffer.from(JSON.stringify(input.parts, null, 2) + '\n') });
  try {
    for (const item of files) {
      const target = await safeWorkPath(input.root, item.relative);
      const before = await existingBytes(target);
      if (before) {
        const same = before.equals(item.bytes)
          || (item.role === 'parts' && Buffer.concat([before, Buffer.from('\n')]).equals(item.bytes));
        if (!same) throw new WorkError('ASSET_NAME_CONFLICT', '作品中已有同名但内容或来源不同的模型文件', 409);
        continue;
      }
      await mkdir(path.dirname(target), { recursive: true });
      await writeAtomic(target, item.bytes);
      drafts.push({ path: item.relative, operation: 'create', role: item.role, beforeHash: null, afterHash: digest(item.bytes), bytes: item.bytes.length, assetId: input.assetId });
    }
    return drafts;
  } catch (error) {
    for (const draft of drafts) {
      try {
        const target = await safeWorkPath(input.root, draft.path);
        const bytes = await existingBytes(target);
        if (bytes && digest(bytes) === draft.afterHash) await rm(target, { force: true });
      } catch { /* best-effort rollback of this operation's new files */ }
    }
    throw error;
  }
}

export interface PackageModuleInput {
  root: string;
  candidateId: string;
  baseVersion: string;
  instanceId: string;
  assetId: string;
  binary: Buffer;
  provenance: ModelProvenance;
  parts?: unknown;
  target: AssetPlacementTarget;
  config: SceneModuleConfig;
}

export async function packageAssetModule(input: PackageModuleInput): Promise<{ ledger: AssetLedger; config: SceneModuleConfig; sourceFile: string }> {
  if (!/^[a-f0-9]{32}$/.test(input.instanceId) || !/^[A-Za-z0-9_-]{1,80}$/.test(input.assetId)) throw new WorkError('INVALID_MODULE', '实例资产编号无效');
  if (input.target.kind !== 'insert') throw new WorkError('INVALID_PLACEMENT_TARGET', '只有普通区域可以插入新模块');
  const match = /^(src\/[A-Za-z0-9_./-]+):([1-9]\d*):([1-9]\d*)$/.exec(input.target.src);
  if (!match) throw new WorkError('INVALID_PLACEMENT_TARGET', '目标源码身份无效');
  const config = parseSceneModuleConfig({ ...input.config, instanceId: input.instanceId, assetId: input.assetId, model: `/assets/${input.assetId}.glb` });
  if (config.instanceId !== input.instanceId) throw new WorkError('INVALID_MODULE', '实例编号不一致');
  const sourceFile = match[1];
  const sourcePath = await safeWorkPath(input.root, sourceFile);
  const sourceBefore = await existingBytes(sourcePath);
  if (!sourceBefore) throw new WorkError('INVALID_PLACEMENT_TARGET', '目标源码不存在', 409);
  const beforeText = sourceBefore.toString('utf8');
  if (scanModuleReferences(beforeText, sourceFile).some(reference => reference.instanceId === input.instanceId)) throw new WorkError('INVALID_MODULE', '实例引用已经存在');
  const afterText = insertModuleSource(beforeText, sourceFile, input.target, input.instanceId);
  const added = scanModuleReferences(afterText, sourceFile).filter(reference => reference.instanceId === input.instanceId);
  if (added.length !== 1 || added[0].dynamic) {
    throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '新增模块必须只有一个静态实例引用', 409);
  }
  const configPath = moduleConfigPath(input.instanceId);
  const componentPath = moduleComponentPath(input.instanceId);
  const configBytes = Buffer.from(JSON.stringify(config, null, 2) + '\n');
  const componentBytes = Buffer.from(moduleComponentSource(input.instanceId));
  for (const relative of [configPath, componentPath]) {
    if (await existingBytes(await safeWorkPath(input.root, relative))) throw new WorkError('MODULE_EXISTS', '实例配置或组件已经存在', 409);
  }
  const drafts: AssetFileDraft[] = await installAssetFiles(input);
  const runtime = await ensureModuleRuntime(input.root);
  if (runtime) drafts.push(runtime);
  const tsconfig = await ensureModuleTsConfig(input.root);
  if (tsconfig) drafts.push(tsconfig);
  const configTarget = await safeWorkPath(input.root, configPath);
  await mkdir(path.dirname(configTarget), { recursive: true });
  await writeAtomic(configTarget, configBytes);
  drafts.push({ path: configPath, operation: 'create', role: 'config', beforeHash: null, afterHash: digest(configBytes), bytes: configBytes.length, assetId: input.assetId, instanceId: input.instanceId });
  const componentTarget = await safeWorkPath(input.root, componentPath);
  await writeAtomic(componentTarget, componentBytes);
  drafts.push({ path: componentPath, operation: 'create', role: 'component', beforeHash: null, afterHash: digest(componentBytes), bytes: componentBytes.length, instanceId: input.instanceId });
  const sourceAfter = Buffer.from(afterText);
  await writeAtomic(sourcePath, sourceAfter);
  drafts.push({ path: sourceFile, operation: 'modify', role: 'source', beforeHash: digest(sourceBefore), afterHash: digest(sourceAfter), bytes: sourceAfter.length, instanceId: input.instanceId });
  const ledger: AssetLedger = {
    schemaVersion: 1, candidateId: input.candidateId, baseVersion: input.baseVersion, instanceId: input.instanceId,
    intent: 'insert', entries: drafts, reference: { action: 'add', file: sourceFile, instanceId: input.instanceId, anchor: `${added[0].line}:${added[0].column}` },
    createdAt: new Date().toISOString(),
  };
  return { ledger, config, sourceFile };
}

export function removeModuleSource(source: string, filename: string, instanceId: string): string {
  const tree = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const component = `SpatialModel${instanceId}`;
  const references: Array<ts.JsxElement | ts.JsxSelfClosingElement> = [];
  function visit(node: ts.Node) {
    if (ts.isJsxSelfClosingElement(node) && node.tagName.getText(tree) === component) references.push(node);
    if (ts.isJsxElement(node) && node.openingElement.tagName.getText(tree) === component) references.push(node);
    ts.forEachChild(node, visit);
  }
  visit(tree);
  if (references.length !== 1) throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '移除模块要求恰好一处静态引用', 409);
  const reference = references[0];
  let text = source;
  const parent = reference.parent;
  if (parent && ts.isJsxFragment(parent)) {
    const children = parent.children.filter(child => !ts.isJsxText(child) || child.text.trim().length > 0);
    if (children.length === 2) {
      const other = children.find(child => child !== reference);
      if (other) text = text.slice(0, parent.getStart(tree)) + text.slice(other.getStart(tree), other.end) + text.slice(parent.end);
      else text = text.slice(0, reference.getStart(tree)) + text.slice(reference.end);
    } else text = text.slice(0, reference.getStart(tree)) + text.slice(reference.end);
  } else text = text.slice(0, reference.getStart(tree)) + text.slice(reference.end);
  const importPath = path.posix.relative(path.posix.dirname(filename), `${SCENE_MODULE_DIRECTORY}/${instanceId}.tsx`).replace(/^(?!\.)/, './');
  const current = ts.createSourceFile(filename, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const imports: ts.ImportDeclaration[] = [];
  function visitImports(node: ts.Node) {
    if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier) && node.moduleSpecifier.text === importPath) imports.push(node);
    ts.forEachChild(node, visitImports);
  }
  visitImports(current);
  if (imports.length !== 1) throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '移除模块要求恰好一处受管导入', 409);
  const statement = imports[0];
  const removeStart = statement.getStart(current);
  let removeEnd = statement.end;
  if (text[removeEnd] === '\r') removeEnd++;
  if (text[removeEnd] === '\n') removeEnd++;
  return text.slice(0, removeStart) + text.slice(removeEnd);
}

export async function findModuleReference(root: string, instanceId: string): Promise<{ file: string; count: number }> {
  if (!/^[a-f0-9]{32}$/.test(instanceId)) throw new WorkError('INVALID_MODULE', '实例编号无效');
  const directory = await safeWorkPath(root, 'src');
  const matches: Array<{ file: string; count: number }> = [];
  async function walk(folder: string, relative: string) {
    for (const entry of await readdir(folder, { withFileTypes: true })) {
      const child = `${relative}/${entry.name}`;
      if (entry.isDirectory()) {
        if (child !== SCENE_MODULE_DIRECTORY) await walk(path.join(folder, entry.name), child);
        continue;
      }
      if (!entry.isFile() || !/\.(?:tsx|ts)$/.test(entry.name)) continue;
      const bytes = await existingBytes(path.join(folder, entry.name));
      if (!bytes) continue;
      const count = scanModuleReferences(bytes.toString('utf8'), child).filter(reference => reference.instanceId === instanceId).length;
      if (count) matches.push({ file: child, count });
    }
  }
  await walk(directory, 'src');
  if (matches.length !== 1 || matches[0].count !== 1) throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '受信实例必须恰好有一处静态引用', 409);
  return matches[0];
}

export async function removeModulePackage(input: { root: string; candidateId: string; baseVersion: string; instanceId: string }): Promise<{ ledger: AssetLedger; sourceFile: string }> {
  const config = await readModuleConfig(input.root, input.instanceId);
  const directory = await safeWorkPath(input.root, 'src');
  const matches: Array<{ file: string; source: string; references: ModuleReference[] }> = [];
  async function walk(folder: string, relative: string) {
    for (const entry of await readdir(folder, { withFileTypes: true })) {
      const child = `${relative}/${entry.name}`;
      if (entry.isDirectory()) {
        if (child !== SCENE_MODULE_DIRECTORY) await walk(path.join(folder, entry.name), child);
        continue;
      }
      if (!entry.isFile() || !/\.(?:tsx|ts)$/.test(entry.name)) continue;
      const bytes = await existingBytes(path.join(folder, entry.name));
      if (!bytes) continue;
      const source = bytes.toString('utf8');
      const references = scanModuleReferences(source, child).filter(reference => reference.instanceId === input.instanceId);
      if (references.length) matches.push({ file: child, source, references });
    }
  }
  await walk(directory, 'src');
  if (matches.length !== 1 || matches[0].references.length !== 1) throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '移除模块要求恰好一处静态引用', 409);
  const target = matches[0];
  const reference = target.references[0];
  if (!reference) throw new WorkError('MODULE_REFERENCE_UNAPPROVED', '移除模块缺少实际引用位置', 409);
  const sourcePath = await safeWorkPath(input.root, target.file);
  const beforeBytes = await existingBytes(sourcePath);
  if (!beforeBytes) throw new WorkError('MODULE_NOT_FOUND', '移除目标源码缺失', 404);
  const afterBytes = Buffer.from(removeModuleSource(target.source, target.file, input.instanceId));
  await writeAtomic(sourcePath, afterBytes);
  const configPath = moduleConfigPath(input.instanceId);
  const componentPath = moduleComponentPath(input.instanceId);
  const configTarget = await safeWorkPath(input.root, configPath);
  const componentTarget = await safeWorkPath(input.root, componentPath);
  const configBytes = await existingBytes(configTarget);
  const componentBytes = await existingBytes(componentTarget);
  if (!configBytes || !componentBytes) throw new WorkError('MODULE_NOT_FOUND', '实例配置或组件缺失', 404);
  await rm(configTarget);
  await rm(componentTarget);
  const entries: LedgerEntry[] = [
    { path: target.file, operation: 'modify', role: 'source', beforeHash: digest(beforeBytes), afterHash: digest(afterBytes), bytes: afterBytes.length, instanceId: input.instanceId },
    { path: configPath, operation: 'delete', role: 'config', beforeHash: digest(configBytes), afterHash: null, bytes: 0, assetId: config.assetId, instanceId: input.instanceId },
    { path: componentPath, operation: 'delete', role: 'component', beforeHash: digest(componentBytes), afterHash: null, bytes: 0, instanceId: input.instanceId },
  ];
  return {
    sourceFile: target.file,
    ledger: {
      schemaVersion: 1, candidateId: input.candidateId, baseVersion: input.baseVersion, instanceId: input.instanceId,
      intent: 'remove', entries, reference: { action: 'remove', file: target.file, instanceId: input.instanceId, anchor: `${reference.line}:${reference.column}` },
      createdAt: new Date().toISOString(),
    },
  };
}


/** Reject a saved clip name that the referenced GLB does not contain. */
export async function assertAnimationClip(root: string, assetId: string, clip: string): Promise<void> {
  if (!clip) return;
  if (!/^[A-Za-z0-9_-]{1,80}$/.test(assetId)) throw new WorkError('INVALID_MODULE', '资产编号无效');
  const file = await safeWorkPath(root, `public/assets/${assetId}.glb`);
  const bytes = await existingBytes(file);
  if (!bytes) throw new WorkError('ASSET_NOT_READY', '实例引用的模型不在作品中', 409);
  let names: string[] = [];
  try {
    const length = bytes.readUInt32LE(12);
    if (bytes.length >= 20 && bytes.toString('ascii', 0, 4) === 'glTF' && 20 + length <= bytes.length) {
      const json = JSON.parse(bytes.toString('utf8', 20, 20 + length)) as { animations?: Array<{ name?: unknown }> };
      names = (json.animations ?? []).map(item => typeof item.name === 'string' ? item.name : '').filter(Boolean);
    }
  } catch { throw new WorkError('INVALID_MODULE', '实例模型无法解析动画片段', 409); }
  if (!names.includes(clip)) throw new WorkError('UNKNOWN_ANIMATION_CLIP', `实例模型没有动画片段 ${clip}`, 409);
}

