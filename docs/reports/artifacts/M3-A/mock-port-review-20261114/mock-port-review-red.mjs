import { spawn, execFileSync } from 'node:child_process';
import { createWriteStream } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cwd = path.join(root, 'apps/server');
const require = createRequire(path.join(cwd, 'package.json'));
const runner = path.join(path.dirname(require.resolve('vitest/package.json')), 'vitest.mjs');
const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
console.log(JSON.stringify({ head, purpose: 'RED: Windows-reserved EACCES currently stops allocation', command: [process.execPath, runner, 'run', 'src/test-support/fetch-listener.test.ts'] }));
const log = createWriteStream(path.join(root, '.data/mock-port-review-red.log'));
const child = spawn(process.execPath, [runner, 'run', 'src/test-support/fetch-listener.test.ts'], { cwd, env: { ...process.env, CI: 'true', NO_COLOR: '1' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
for (const stream of [child.stdout, child.stderr]) stream.on('data', chunk => { log.write(chunk); process.stdout.write(chunk); });
child.on('error', error => { console.error(error.message); process.exitCode = 1; });
const result = await new Promise(resolve => child.on('close', (code, signal) => resolve({ code, signal })));
await new Promise(resolve => log.end(resolve));
console.log(JSON.stringify(result));
if (result.code !== 0 || result.signal) process.exitCode = 1;
